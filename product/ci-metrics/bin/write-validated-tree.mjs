// Writes the tested-tree validation manifest for #562 (phase A: shadow provenance).
//
// Runs in the non-authoritative metrics-report job from the merged run record. The manifest records the
// exact checked-out commit and tree, PR/base/head identity, event, workflow revision, per-job results,
// and verified totals. It is produced only when the required gate and every selected product job
// succeeded, and it is explicitly labelled shadow because the same-workflow checkout is PR-controlled on
// pull_request runs. Phase B enforcement (skipping the post-merge full gate) is not performed here.

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { dirname } from 'node:path'

const env = (name) => process.env[name] ?? ''

function bounded(value, max) {
  return value === null || value === undefined ? null : String(value).slice(0, max)
}

function main() {
  const recordPath = env('VALIDATED_RUN_METRICS_PATH')
  const outputPath = env('VALIDATED_TREE_OUTPUT_PATH')
  if (!recordPath || !existsSync(recordPath) || !outputPath) {
    console.error('[ci-metrics] VALIDATED_RUN_METRICS_PATH (existing file) and VALIDATED_TREE_OUTPUT_PATH are required.')
    process.exit(2)
  }
  let record
  try {
    record = JSON.parse(readFileSync(recordPath, 'utf8'))
  } catch (error) {
    console.error(`[ci-metrics] Could not read the run record: ${error.message}`)
    process.exit(1)
  }

  const jobs = Array.isArray(record.jobs) ? record.jobs : []
  const gate = jobs.find((job) => job.instance === 'gate')
  const selected = jobs.filter((job) => job.result === 'success' || job.result === 'failure' || job.result === 'cancelled')
  const failedOrCancelled = jobs.filter((job) => job.result === 'failure' || job.result === 'cancelled')
  const gatePassed = gate?.result === 'success'
  const allSelectedPassed = selected.every((job) => job.result === 'success')
  const counts = record.counts ?? {}

  const manifest = {
    schemaVersion: 'aerolink-validated-tree/v1',
    provenance: 'shadow',
    provenanceReason: 'Generated by same-workflow code; trusted post-run validation is phase B.',
    repository: bounded(record.run?.repository, 200),
    workflow: bounded(record.run?.workflow, 200),
    workflowRef: bounded(record.run?.workflowRef, 300),
    run: {
      id: record.run?.id ?? null,
      attempt: record.run?.attempt ?? null,
      event: bounded(record.run?.event, 50),
    },
    pullRequest: {
      number: record.run?.pr ?? null,
      baseSha: bounded(record.run?.baseSha, 40),
      headSha: bounded(record.run?.headSha, 40),
    },
    checkedOut: {
      commitSha: bounded(record.run?.sha, 40),
      treeSha: bounded(record.run?.tree, 40),
      ref: bounded(record.run?.ref, 200),
    },
    event: bounded(record.run?.event, 50),
    classifications: record.classifications ?? null,
    gates: {
      selected: selected.map((job) => ({ instance: job.instance, result: job.result })),
      skipped: Array.isArray(record.skipped) ? record.skipped.map((job) => ({ instance: job.instance, reason: bounded(job.reason, 300) })) : [],
      missing: Array.isArray(record.missing) ? record.missing.map((entry) => ({ job: bounded(entry.job, 120), reason: bounded(entry.reason, 300) })) : [],
      gatePassed,
      allSelectedPassed,
    },
    verifiedTotals: {
      expected: counts.expected ?? null,
      executed: counts.executed ?? null,
      passed: counts.passed ?? null,
      failed: counts.failed ?? null,
      skipped: counts.skipped ?? null,
      flaky: counts.flaky ?? null,
    },
    validatedAt: env('VALIDATED_AT') || new Date().toISOString(),
    canAuthorizePostMergeSkip: gatePassed && allSelectedPassed && failedOrCancelled.length === 0 && record.missingTotal === 0,
  }

  mkdirSync(dirname(outputPath), { recursive: true })
  writeFileSync(outputPath, `${JSON.stringify(manifest, null, 2)}\n`, 'utf8')
  console.log(`[ci-metrics] Wrote validated-tree manifest (tree ${manifest.checkedOut.treeSha}, authorize=${manifest.canAuthorizePostMergeSkip}).`)
}

main()
